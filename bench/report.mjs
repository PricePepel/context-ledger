// Markdown rendering of an M0 benchmark report. Only numbers, IDs and fixed text
// reach the output; no transcript text is copied into the report.

const table = (header, rows) => [
  `| ${header.join(' | ')} |`,
  `| ${header.map(() => '---').join(' | ')} |`,
  ...rows.map(row => `| ${row.join(' | ')} |`),
];

const percent = share => `${(share * 100).toFixed(1)}%`;
const usd = value => `$${value.toFixed(3)}`;

function partyRows(report, render) {
  return report.results.flatMap(result => Object.entries(result.parties)
    .map(([name, party]) => [result.size, `${name} (${party.provider})`, ...render(party, result)]));
}

const sizesWhere = (report, test) => report.results.filter(result => Object.values(result.parties).some(test)).map(result => result.size);
const shareRange = (report, pick) => {
  const shares = report.results.flatMap(result => Object.values(result.parties).map(pick));
  return `${percent(Math.min(...shares))} to ${percent(Math.max(...shares))}`;
};
const listSizes = sizes => (sizes.length ? `${sizes.join(', ')} turns` : 'no size');

function verdict(handoffAhead, total) {
  if (handoffAhead.length === total) {
    return 'So the graph context is smaller, but it is not the more cache-stable format here: at every size a handoff with its IDs held constant keeps a larger share of its characters as a common prefix than the graph context.';
  }
  if (handoffAhead.length === 0) return 'At every size the graph context keeps a larger share of its characters as a common prefix than the handoff, even with the handoff\'s IDs held constant.';
  return `With IDs held constant the handoff keeps the larger prefix share at ${listSizes(handoffAhead)} and the graph context at the other sizes.`;
}

/** The cache-prefix conclusion, computed from the results rather than fixed text. */
function cacheConclusion(report) {
  const graphEligible = sizesWhere(report, party => party.cachePrefix.graph.cacheEligible);
  const handoffEligible = sizesWhere(report, party => party.cachePrefix.idsHeldConstant.handoff.cacheEligible);
  const handoffAsIsEligible = sizesWhere(report, party => party.cachePrefix.handoff.cacheEligible);
  const endsAtId = report.results.every(result => Object.values(result.parties).every(party => party.cachePrefix.handoffPrefixEndsInSessionLine));
  return [
    `As is, the handoff keeps ${shareRange(report, party => party.cachePrefix.handoff.share)} of its characters as a common prefix`
      + (endsAtId ? ', and at every size the prefix ends inside its `Session:` line, because the session ID is a hash of the whole transcript and changes with every append. ' : '. ')
      + `With session and graph IDs held constant the handoff keeps ${shareRange(report, party => party.cachePrefix.idsHeldConstant.handoff.share)}: after the ID line it is append-only. `
      + `The graph context keeps ${shareRange(report, party => party.cachePrefix.graph.share)} as is and ${shareRange(report, party => party.cachePrefix.idsHeldConstant.graph.share)} with IDs held constant; `
      + 'its prefix ends in the middle because the new action also adds an `advances` edge, and the edges section comes before links and actions.',
    '',
    `Cache-eligible stable prefix (at least ${report.cacheMinimumTokens} estimated tokens): graph context at ${listSizes(graphEligible)}; `
      + `handoff as is at ${listSizes(handoffAsIsEligible)}; handoff with IDs held constant at ${listSizes(handoffEligible)}. `
      + verdict(sizesWhere(report, party => party.cachePrefix.idsHeldConstant.handoff.share > party.cachePrefix.graph.share), report.results.length),
  ];
}

export function renderMarkdown(report) {
  const lines = [
    '# M0 benchmark: graph context vs Markdown handoff',
    '',
    `Generated by \`bench/m0.mjs\` on ${report.date} at commit \`${report.gitCommit}\`${report.gitDirty
      ? ' with uncommitted changes to `bench/`, `src/`, `schemas/` or `package.json`, so that commit alone may not reproduce these numbers' : ''}, seed ${report.seed}. `
      + 'All transcripts are synthetic. Everything except timings, date, commit and machine is deterministic for a seed.',
    '',
    'Reproduce:',
    '',
    '```sh',
    `${report.command} --markdown docs/benchmark.md`,
    '```',
    '',
    `Machine: Node ${report.machine.node}, ${report.machine.platform}, ${report.machine.cpus} x ${report.machine.cpu}.`,
    '',
    'Each size is the number of conversation turns per party. Party `mara` is a Claude Code JSONL transcript and party `teo` a Codex rollout; '
      + '`teo` links to `mara` with matches, conflicts and answers, and the two graphs open one room.',
    '',
    '## 1. Size',
    '',
    'Method: characters and estimated tokens come from the API meter (`GET /api/graphs/:id/context`). '
      + 'Tokens are estimates, ceil(chars / 4), not tokenizer counts. The character ratio is the primary figure because it does not depend on the estimate.',
    '',
    ...table(['Turns', 'Party', 'Transcript bytes', 'Handoff chars', 'Graph chars', 'Graph / handoff chars', 'Handoff tokens (est.)', 'Graph tokens (est.)', 'Saved (est.)'],
      partyRows(report, party => [party.transcriptBytes, party.size.handoffCharacters, party.size.graphCharacters,
        percent(party.size.characterRatio), party.size.handoffTokensEstimate, party.size.graphTokensEstimate, percent(party.size.savedShare)])),
    '',
    '## 2. Fact recall',
    '',
    'Method: a planted fact counts as present when its label and its cited line appear together: in the graph context, on the node line with `L<line>`; '
      + 'in the handoff, inside the section headed with that line. Links count when the context lists them. '
      + 'The benchmark builds the packets itself (no LLM extraction), so 1.0 is a guard that rendering drops no planted fact, not a claim about extraction quality.',
    '',
    ...table(['Turns', 'Party', 'Planted facts', 'Graph recall', 'Handoff recall', 'Link recall'],
      partyRows(report, party => [party.recall.graph.planted, party.recall.graph.recall, party.recall.handoff.recall,
        party.recall.links ? `${party.recall.links.recall} (${party.recall.links.planted} links)` : 'n/a'])),
    '',
    '## 3. Cache-prefix stability',
    '',
    `Method: ${report.appendTurns} turns are appended to the transcript and it is imported again. The store keys a session by the hash of its transcript, `
      + 'so the longer transcript becomes a new session. A revised graph with the same nodes plus one new action is published against it. '
      + 'The table shows the longest common leading prefix of the old and new output, in characters, as a share of the new output, '
      + 'once as is and once comparing the texts with every session and graph ID replaced by the same placeholder on both sides ("IDs constant"), '
      + 'so a single changed ID line does not decide the comparison. Both shares use the original new output as the denominator: '
      + 'a placeholder inside the matching prefix counts as the full ID it stands for. Tokens are estimated as characters / 4, like the meter. '
      + `A prefix counts as cache-eligible only from ${report.cacheMinimumTokens} estimated tokens, the safe minimum across Anthropic's older models and OpenAI (the newest Claude models accept 512).`,
    '',
    ...table(['Turns', 'Party', 'Graph share', 'Graph tokens (est.)', 'Graph share, IDs constant', 'Handoff share', 'Handoff tokens (est.)',
      'Handoff share, IDs constant', 'Handoff tokens, IDs constant (est.)', 'Revised graph recall'],
    partyRows(report, party => {
      const { graph, handoff, idsHeldConstant: constant } = party.cachePrefix;
      const tokens = prefix => `${prefix.prefixTokensEstimate}${prefix.cacheEligible ? ' (eligible)' : ''}`;
      return [percent(graph.share), tokens(graph), percent(constant.graph.share), percent(handoff.share), tokens(handoff),
        percent(constant.handoff.share), tokens(constant.handoff), party.cachePrefix.revisedRecall.recall];
    })),
    '',
    ...cacheConclusion(report),
    '',
    '## 4. Order invariance',
    '',
    'Method: a copy of each packet with nodes, evidence lines, edges and links in a seeded random order is published; it must return the same graph ID. '
      + '"Input reordered" checks that the shuffle really changed the order. The graph ID is the independent check: the store derives it from the canonical packet '
      + 'and keeps the first row for an ID, so the identical context follows from the same ID and is an end-to-end guard, not a separate guarantee.',
    '',
    ...table(['Turns', 'Party', 'Input reordered', 'Same graph ID', 'Identical context (implied)'],
      partyRows(report, party => [party.orderInvariance.inputReordered, party.orderInvariance.sameGraphId, party.orderInvariance.identicalContext])),
    '',
    '## 5. Latency',
    '',
    `Method: wall-clock time of ${report.reps} sequential HTTP requests from the benchmark process to the local server, nearest-rank p50 and p95 in ms. `
      + "Publish re-sends `teo`'s packet (validation, hashing and an insert that ignores the existing row); context reads and renders `teo`'s graph; room open re-opens the room. "
      + 'Timings vary by machine and are excluded from determinism checks.',
    '',
    ...table(['Turns', 'Publish p50', 'Publish p95', 'Context p50', 'Context p95', 'Room open p50', 'Room open p95'],
      report.results.map(result => [result.size, result.latencyMs.publish.p50, result.latencyMs.publish.p95,
        result.latencyMs.context.p50, result.latencyMs.context.p95, result.latencyMs.roomOpen.p50, result.latencyMs.roomOpen.p95])),
    '',
    '## 6. Content mix (direction of the chars/4 error)',
    '',
    'Method: share of characters that are punctuation or symbols, decimal digits, or non-ASCII (Unicode property classes). '
      + 'These usually take more tokens per character than prose, so the side with more of them is likely underestimated more by chars/4.',
    '',
    ...table(['Turns', 'Party', 'Handoff punct.', 'Graph punct.', 'Handoff digits', 'Graph digits', 'Handoff non-ASCII', 'Graph non-ASCII'],
      partyRows(report, party => [percent(party.contentMix.handoff.punctuationShare), percent(party.contentMix.graph.punctuationShare),
        percent(party.contentMix.handoff.digitShare), percent(party.contentMix.graph.digitShare),
        percent(party.contentMix.handoff.nonAsciiShare), percent(party.contentMix.graph.nonAsciiShare)])),
    '',
    '## 7. Cost illustration',
    '',
    `Illustration only, on estimated tokens: input cost in USD per 1,000 handoffs of \`teo\`'s context at list prices seen on ${report.prices.seen}. `
      + 'Uncached prices the base output. Steady state prices the next request (the revised output from section 3) with its cache-eligible stable prefix at the cache-hit rate and the rest at the base rate; prefix and total are both estimated from characters, and the cached part never exceeds the total. It assumes the next request arrives within the cache lifetime '
      + '(5 minutes by default) and ignores cache-write premiums. Below the cache minimum it equals the uncached cost. '
      + 'The graph uses its as-is prefix (its IDs are already at the end). The handoff steady state uses the prefix with IDs held constant, '
      + 'that is, a handoff whose session ID line were moved after the turns; the current handoff format cannot reach it.',
    '',
    ...table(['Turns', 'Model', 'Handoff uncached', 'Handoff steady state, IDs constant', 'Graph uncached', 'Graph steady state'],
      report.results.flatMap(result => result.parties.teo.costPerThousandHandoffsUsd.map(cost => [result.size,
        cost.verified ? cost.model : `${cost.model} (unverified)`, usd(cost.handoffUncached), usd(cost.handoffSteadyStateIdsConstant),
        usd(cost.graphUncached), usd(cost.graphSteadyState)]))),
    '',
    'Price sources:',
    '',
    ...report.prices.models.map(price => `- ${price.model}: $${price.input} input, $${price.cacheHit} cache hit per million tokens. ${price.source}${price.verified ? '' : '. Unverified: taken from an aggregator citing an OpenAI pricing capture; the official page could not be opened.'}`),
    '',
    '## Method and limits',
    '',
    '- Inputs are synthetic negotiations from a seeded PRNG (mulberry32). Most turns are filler work chatter; planted facts (about sqrt(turns) + 4 per party) sit at known lines. Real sessions have longer turns, tool output and code, so absolute sizes and ratios will differ.',
    '- The benchmark writes the graph packets itself. It measures storage, canonicalisation and rendering through the real HTTP API, not how well an agent extracts a graph from a transcript.',
    '- Token figures are estimated as characters / 4 and are not tokenizer counts. Real counts vary by model (Claude 4.7 and later tokenizers emit about 30% more tokens for the same text) and by content: structured text, digits and code usually yield more tokens per character than prose, so the token saving may differ from the character saving. Section 6 shows the content mix of each side.',
    '- The graph context is compared with the full Markdown handoff of the same transcript, which is the baseline the API meter uses. A hand-written summary would be a different, smaller baseline.',
    '- Cache savings need a prefix above the provider minimum and a follow-up request within the cache lifetime. Changing tools, the system prompt or thinking settings invalidates a cache whatever Context Ledger outputs.',
    '- Input limits: sizes run from 2 to 9215 turns, because the revised packet (about sqrt(turns) + 5 nodes) must fit the v2 schema limit of 100 nodes; each import body must stay under the server\'s 8 MiB request limit; seeds run from 0 to 4294967295. The benchmark checks these before it starts the server.',
    '- The server runs as a child process on a free loopback port with a fresh temporary database, which is deleted at the end, also on an error or on SIGINT, SIGTERM or SIGHUP (a signal writes no report and exits with 128 + the signal number). Latency includes local HTTP and JSON overhead and is a single-machine measurement.',
    '',
  ];
  return lines.join('\n');
}
