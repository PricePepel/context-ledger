// Markdown rendering of an M0 benchmark report. Only numbers, IDs and fixed text
// reach the output; no transcript text is copied into the report.

const table = (header, rows) => [
  `| ${header.join(' | ')} |`,
  `| ${header.map(() => '---').join(' | ')} |`,
  ...rows.map(row => `| ${row.join(' | ')} |`),
];

const percent = share => `${(share * 100).toFixed(1)}%`;
const usd = value => `$${value.toFixed(3)}`;

function partyRows(report, render) {
  return report.results.flatMap(result => Object.entries(result.parties)
    .map(([name, party]) => [result.size, `${name} (${party.provider})`, ...render(party, result)]));
}

export function renderMarkdown(report) {
  const lines = [
    '# M0 benchmark: graph context vs Markdown handoff',
    '',
    `Generated by \`bench/m0.mjs\` on ${report.date} at commit \`${report.gitCommit}\`, seed ${report.seed}. `
      + 'All transcripts are synthetic. Everything except timings, date, commit and machine is deterministic for a seed.',
    '',
    'Reproduce:',
    '',
    '```sh',
    `${report.command} --markdown docs/benchmark.md`,
    '```',
    '',
    `Machine: Node ${report.machine.node}, ${report.machine.platform}, ${report.machine.cpus} x ${report.machine.cpu}.`,
    '',
    'Each size is the number of conversation turns per party. Party `mara` is a Claude Code JSONL transcript and party `teo` a Codex rollout; '
      + '`teo` links to `mara` with matches, conflicts and answers, and the two graphs open one room.',
    '',
    '## 1. Size',
    '',
    'Method: characters and estimated tokens come from the API meter (`GET /api/graphs/:id/context`). '
      + 'Tokens are estimates, ceil(chars / 4), not tokenizer counts. The character ratio is the primary figure because it does not depend on the estimate.',
    '',
    ...table(['Turns', 'Party', 'Transcript bytes', 'Handoff chars', 'Graph chars', 'Graph / handoff chars', 'Handoff tokens (est.)', 'Graph tokens (est.)', 'Saved (est.)'],
      partyRows(report, party => [party.transcriptBytes, party.size.handoffCharacters, party.size.graphCharacters,
        percent(party.size.characterRatio), party.size.handoffTokensEstimate, party.size.graphTokensEstimate, percent(party.size.savedShare)])),
    '',
    '## 2. Fact recall',
    '',
    'Method: a planted fact counts as present when its label and its cited line appear together: in the graph context, on the node line with `L<line>`; '
      + 'in the handoff, inside the section headed with that line. Links count when the context lists them. '
      + 'The benchmark builds the packets itself (no LLM extraction), so 1.0 is a guard that rendering drops no planted fact, not a claim about extraction quality.',
    '',
    ...table(['Turns', 'Party', 'Planted facts', 'Graph recall', 'Handoff recall', 'Link recall'],
      partyRows(report, party => [party.recall.graph.planted, party.recall.graph.recall, party.recall.handoff.recall,
        party.recall.links ? `${party.recall.links.recall} (${party.recall.links.planted} links)` : 'n/a'])),
    '',
    '## 3. Cache-prefix stability',
    '',
    `Method: ${report.appendTurns} turns are appended to the transcript and it is imported again. The store keys a session by the hash of its transcript, `
      + 'so the longer transcript becomes a new session. A revised graph with the same nodes plus one new action is published against it. '
      + 'The table shows the longest common leading byte prefix of the old and new output as a share of the new output. '
      + `A prefix counts as cache-eligible only from ${report.cacheMinimumTokens} estimated tokens, the safe minimum across Anthropic's older models and OpenAI (the newest Claude models accept 512).`,
    '',
    ...table(['Turns', 'Party', 'Graph prefix share', 'Graph prefix tokens (est.)', 'Graph cache-eligible', 'Handoff prefix share', 'Handoff prefix tokens (est.)', 'Revised graph recall'],
      partyRows(report, party => [percent(party.cachePrefix.graph.share), party.cachePrefix.graph.prefixTokensEstimate,
        party.cachePrefix.graph.cacheEligible ? 'yes' : 'no', percent(party.cachePrefix.handoff.share),
        party.cachePrefix.handoff.prefixTokensEstimate, party.cachePrefix.revisedRecall.recall])),
    '',
    'The Markdown handoff prints the session ID in its fifth line, and the session ID changes with every append, so its common prefix ends there. '
      + 'The graph context keeps the session and graph IDs in its last section, but its prefix ends earlier than the action section: '
      + 'the new action also adds an `advances` edge, and the edges section comes before links and actions, so the change lands in the middle of the output. '
      + 'Here the stable prefix stays below the cache minimum at every size.',
    '',
    '## 4. Order invariance',
    '',
    'Method: a copy of each packet with nodes, evidence lines, edges and links in a seeded random order is published; it must return the same graph ID and a byte-identical context.',
    '',
    ...table(['Turns', 'Party', 'Same graph ID', 'Identical context'],
      partyRows(report, party => [party.orderInvariance.sameGraphId, party.orderInvariance.identicalContext])),
    '',
    '## 5. Latency',
    '',
    `Method: wall-clock time of ${report.reps} sequential HTTP requests from the benchmark process to the local server, nearest-rank p50 and p95 in ms. `
      + "Publish re-sends `teo`'s packet (validation, hashing and an insert that ignores the existing row); context reads and renders `teo`'s graph; room open re-opens the room. "
      + 'Timings vary by machine and are excluded from determinism checks.',
    '',
    ...table(['Turns', 'Publish p50', 'Publish p95', 'Context p50', 'Context p95', 'Room open p50', 'Room open p95'],
      report.results.map(result => [result.size, result.latencyMs.publish.p50, result.latencyMs.publish.p95,
        result.latencyMs.context.p50, result.latencyMs.context.p95, result.latencyMs.roomOpen.p50, result.latencyMs.roomOpen.p95])),
    '',
    '## 6. Content mix (direction of the chars/4 error)',
    '',
    'Method: share of characters that are punctuation or symbols, decimal digits, or non-ASCII (Unicode property classes). '
      + 'These usually take more tokens per character than prose, so the side with more of them is likely underestimated more by chars/4.',
    '',
    ...table(['Turns', 'Party', 'Handoff punct.', 'Graph punct.', 'Handoff digits', 'Graph digits', 'Handoff non-ASCII', 'Graph non-ASCII'],
      partyRows(report, party => [percent(party.contentMix.handoff.punctuationShare), percent(party.contentMix.graph.punctuationShare),
        percent(party.contentMix.handoff.digitShare), percent(party.contentMix.graph.digitShare),
        percent(party.contentMix.handoff.nonAsciiShare), percent(party.contentMix.graph.nonAsciiShare)])),
    '',
    '## 7. Cost illustration',
    '',
    `Illustration only, on estimated tokens: input cost in USD per 1,000 handoffs of \`teo\`'s context at list prices seen on ${report.prices.seen}. `
      + 'Steady state prices the cache-eligible stable prefix (section 3) at the cache-hit rate and the rest at the base rate; it assumes the next request arrives within the cache lifetime '
      + '(5 minutes by default) and ignores cache-write premiums. Below the cache minimum it equals the uncached cost.',
    '',
    ...table(['Turns', 'Model', 'Handoff uncached', 'Graph uncached', 'Graph steady state'],
      report.results.flatMap(result => result.parties.teo.costPerThousandHandoffsUsd.map(cost => [result.size,
        cost.verified ? cost.model : `${cost.model} (unverified)`, usd(cost.handoffUncached), usd(cost.graphUncached), usd(cost.graphSteadyState)]))),
    '',
    'Price sources:',
    '',
    ...report.prices.models.map(price => `- ${price.model}: $${price.input} input, $${price.cacheHit} cache hit per million tokens. ${price.source}${price.verified ? '' : '. Unverified: taken from an aggregator citing an OpenAI pricing capture; the official page could not be opened.'}`),
    '',
    '## Method and limits',
    '',
    '- Inputs are synthetic negotiations from a seeded PRNG (mulberry32). Most turns are filler work chatter; planted facts (about sqrt(turns) + 4 per party) sit at known lines. Real sessions have longer turns, tool output and code, so absolute sizes and ratios will differ.',
    '- The benchmark writes the graph packets itself. It measures storage, canonicalisation and rendering through the real HTTP API, not how well an agent extracts a graph from a transcript.',
    '- Token figures are estimated as characters / 4 and are not tokenizer counts. Real counts vary by model (Claude 4.7 and later tokenizers emit about 30% more tokens for the same text) and by content: structured text, digits and code usually yield more tokens per character than prose, so the token saving may differ from the character saving. Section 6 shows the content mix of each side.',
    '- The graph context is compared with the full Markdown handoff of the same transcript, which is the baseline the API meter uses. A hand-written summary would be a different, smaller baseline.',
    '- Cache savings need a prefix above the provider minimum and a follow-up request within the cache lifetime. Changing tools, the system prompt or thinking settings invalidates a cache whatever Context Ledger outputs.',
    '- The server runs as a child process on a free loopback port with a fresh temporary database, which is deleted at the end. Latency includes local HTTP and JSON overhead and is a single-machine measurement.',
    '',
  ];
  return lines.join('\n');
}
